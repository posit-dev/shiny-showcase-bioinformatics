# Grouping variables come from the dataset's metadata columns (everything but
# the sample id), with friendly labels for the known clinical columns and a
# prettified fallback for any others (e.g. an uploaded dataset's columns).
.pretty <- c(
  group = "Sample group",
  subtype = "Receptor subtype",
  er_status = "ER status",
  pr_status = "PR status",
  her2_status = "HER2 status",
  stage = "Tumor stage",
  histology = "Histology"
)
make_group_choices <- function(metadata) {
  cols <- setdiff(names(metadata), "sample")
  stats::setNames(
    cols,
    ifelse(
      cols %in% names(.pretty),
      .pretty[cols],
      tools::toTitleCase(gsub("_", " ", cols))
    )
  )
}

# Collapsible per-card guidance: a small muted toggle that expands help inline.
