          )
        ),
        div(
          class = "ds-actions",
          if (!is.null(info$portal)) {
            tags$a(
              href = info$portal,
              target = "_blank",
              rel = "noopener",
              class = "btn-line",
              icon("up-right-from-square"),
              paste0(" ", info$portal_label %||% "Data portal")
            )
          },
          tags$a(
            class = "ds-more",
            onclick = "SG.nav('About')",
            "Read more on the About page →"
          )
        )
      )
    )
  })

  # --- Assistant: scoped, tool-using BYOK chat ----------------------------
  # A plain (non-reactive) mirror of the app's current state. The assistant's
  # tools read it directly, so they are safe to call mid-stream (outside any
  # reactive context); it is kept current by an observer at the end of server().
  chat_state <- new.env(parent = emptyenv())

  # Compact "g" p-value formatting for the read tools.
  .fmt_p <- function(x) formatC(x, format = "g", digits = 3)

  # Hard-scoped: the assistant only helps with THIS app + dataset, reads live
  # state through its tools, and declines anything off-topic.
  sig_system_prompt <- paste(
    "You are the Signature Scoring assistant, embedded in an app that scores",
    "MSigDB Hallmark gene sets across samples of one loaded dataset (e.g.",
    "TCGA-BRCA tumour vs normal, with clinical annotations) and ranks the",
    "signatures between two groups. Your ONLY job is to help the user explore",
    "and interpret THIS app: its current dataset, scoring method, and contrast,",
    "and its views -- the signature volcano, the ranking table, signature",
    "detail, the score heatmap, and the leading-edge (pathway) genes.",
    "",
    "Before answering about a view, call the matching read tool for its live",
    "state: dataset_info, describe_ranking, describe_volcano, describe_signature,",
    "describe_leading_edge. Never invent signature names, gene names, counts, or",
    "statistics -- quote the tool output. Explain single-sample pathway-activity",
    "scores (ssGSEA, singscore, module z-score, mean), score differences,",
    "p-values, and Hallmark pathway terms plainly.",
    "",
    "You can also DRIVE the app's controls when the user asks -- then briefly say",
    "what you changed:",
    "- set_method: change the scoring method (re-scores every signature).",
    "- set_contrast: change the grouping variable and/or the two levels being",
    "  contrasted (drives the ranking, volcano, heatmap, and detail together).",
    "- set_signature: focus a signature in Signature detail and Pathway genes.",
    "- set_signature_count: how many top signatures the score heatmap shows.",
    "- set_volcano: the volcano's significance threshold and label count.",
    "After changing a control, you may re-read the relevant view to interpret it.",
    "",
    "Refuse anything outside this app and dataset: for off-topic or general",
    "questions, briefly decline and point back to what the app can do. Be concise.",
    sep = "\n"
  )

  # Read/interpret tools over the state mirror, plus control tools that drive the
  # inputs (guarded so the app still loads without ellmer). Each read tool
  # returns a compact summary computed from the mirrored state.
  sig_tools <- list()
  if (requireNamespace("ellmer", quietly = TRUE)) {
    sig_tools <- list(
      ellmer::tool(
        function() {
          meta <- chat_state$dataset$metadata
          grp <- if ("group" %in% names(meta)) table(meta$group) else NULL
          paste(
            c(
              paste0("Dataset: ", chat_state$dataset_label, "."),
              paste0(
                "Samples: ",
                nrow(meta),
                "; genes measured: ",
                nrow(chat_state$dataset$expression),
                "; Hallmark signatures: ",
                length(chat_state$dataset$signatures),
                "."
              ),
              if (!is.null(grp)) {
                paste0(
                  "Sample groups: ",
                  paste(
                    sprintf("%s (n=%d)", names(grp), as.integer(grp)),
                    collapse = ", "
                  ),
                  "."
                )
              },
              paste0(
                "Metadata columns: ",
                paste(setdiff(names(meta), "sample"), collapse = ", "),
                "."
              ),
              paste0("Scoring method: ", chat_state$method_label, "."),
              paste0(
                "Current contrast: ",
                chat_state$group_label %||% chat_state$group_col,
                " (",
                chat_state$level2,
                " vs ",
                chat_state$level1,
                ")."
              )
            ),
            collapse = "\n"
          )
        },
        name = "dataset_info",
        description = paste(
          "Meta on the loaded dataset: sample / gene / signature counts, groups,",
          "metadata columns, the current scoring method, and the current",
          "group contrast."
        )
      ),
      ellmer::tool(
        function() {
          r <- chat_state$ranking
          if (is.null(r) || nrow(r) == 0) {
            return("No ranking is available yet (pick two contrast levels).")
          }
          sig <- r[!is.na(r$padj) & r$padj <= chat_state$vp, , drop = FALSE]
          join <- function(d) {
            if (nrow(d) == 0) {
              return("(none)")
            }
            paste(
              sprintf(
                "%s (diff %.2f, padj %s)",
                d$signature,
                d$diff,
                .fmt_p(d$padj)
              ),
              collapse = "; "
            )
          }
          up2 <- utils::head(sig[order(-sig$diff), , drop = FALSE], 6)
          up1 <- utils::head(sig[order(sig$diff), , drop = FALSE], 6)
          paste(
            sprintf(
              "Contrast %s vs %s (diff = %s - %s); method %s.",
              chat_state$level2,
              chat_state$level1,
              chat_state$level2,
              chat_state$level1,
              chat_state$method_label
            ),
            sprintf(
              "%d of %d signatures are significant at padj <= %g.",
              nrow(sig),
              nrow(r),
              chat_state$vp
            ),
            paste0("Higher in ", chat_state$level2, ": ", join(up2), "."),
            paste0("Higher in ", chat_state$level1, ": ", join(up1), "."),
            sep = "\n"
          )
        },
        name = "describe_ranking",
        description = paste(
          "Ranking summary: how many signatures are significant at the current",
          "threshold, and the signatures most elevated in each of the two groups."
        )
      ),
      ellmer::tool(
        function() {
          r <- chat_state$ranking
          if (is.null(r) || nrow(r) == 0) {
            return("No signatures are scored yet.")
          }
          r <- r[!is.na(r$diff) & !is.na(r$padj), , drop = FALSE]
          sig <- r[r$padj <= chat_state$vp, , drop = FALSE]
          join <- function(d) {
            if (nrow(d) == 0) "(none)" else paste(d$signature, collapse = ", ")
          }
          paste(
            sprintf(
              "Volcano over %d scored signatures at padj <= %g (%s vs %s).",
              nrow(r),
              chat_state$vp,
              chat_state$level2,
              chat_state$level1
            ),
            sprintf("Significant: %d.", nrow(sig)),
            paste0(
              "Most significant: ",
              join(utils::head(sig[order(sig$padj), , drop = FALSE], 8)),
              "."
            ),
            paste0(
              "Largest score differences: ",
              join(utils::head(sig[order(-abs(sig$diff)), , drop = FALSE], 8)),
              "."
            ),
            sep = "\n"
          )
        },
        name = "describe_volcano",
        description = paste(
          "Volcano summary: how many signatures are significant, the most",
          "significant signatures, and the largest score differences."
        )
      ),
      ellmer::tool(
        function() {
          sig <- chat_state$selected_sig
          r <- chat_state$ranking
          if (is.null(sig) || is.null(r)) {
            return("No signature is selected yet.")
          }
          row <- r[r$signature == sig, , drop = FALSE]
          if (nrow(row) == 0) {
            return(paste0("'", sig, "' is not in the current ranking."))
          }
          mean_cols <- grep("^mean_", names(r), value = TRUE)
          means <- paste(
            sprintf(
              "%s = %.3f",
              sub("^mean_", "mean ", mean_cols),
              as.numeric(row[mean_cols])
            ),
            collapse = "; "
          )
          paste0(
            "Selected signature: ",
            sig,
            ". ",
            means,
            ". Difference (",
            chat_state$level2,
            " - ",
            chat_state$level1,
            ") = ",
            sprintf("%.3f", row$diff),
            "; p = ",
            .fmt_p(row$pvalue),
            ", padj = ",
            .fmt_p(row$padj),
            "."
          )
        },
        name = "describe_signature",
        description = paste(
          "Summary of the currently selected signature: its mean score in each",
          "group, the between-group difference, and its p / adjusted-p."
        )
      ),
      ellmer::tool(
        function() {
          sig <- chat_state$selected_sig
          if (is.null(sig)) {
            return("No signature is selected yet.")
          }
          genes <- intersect(
            chat_state$dataset$signatures[[sig]],
            rownames(chat_state$expr)
          )
          cm <- chat_state$contrast_meta
          if (length(genes) == 0 || is.null(cm)) {
            return("No member genes / contrast available for this signature.")
          }
          le_expr <- chat_state$expr[, cm$sample, drop = FALSE]
          le <- signature_leading_edge(
            le_expr,
            genes,
            cm[[chat_state$group_col]],
            chat_state$level1,
            chat_state$level2
          )
          if (nrow(le) == 0) {
            return("No leading-edge genes for this signature.")
          }
          top <- utils::head(le, 12)
          paste0(
            sig,
            " has ",
            length(genes),
            " member genes in the expression matrix. ",
            "Top leading-edge genes by |difference| (",
            chat_state$level2,
            " - ",
            chat_state$level1,
            "): ",
            paste(sprintf("%s (Δ %.2f)", top$gene, top$diff), collapse = "; "),
            "."
          )
        },
        name = "describe_leading_edge",
        description = paste(
          "Leading-edge summary for the selected signature: how many member",
          "genes are present and the genes with the largest between-group",
          "expression difference (its leading edge)."
        )
      ),
      # --- Control tools: drive the app's inputs (updateXxxInput / DT proxy are
      # all safe to call mid-stream, outside a reactive context).
      ellmer::tool(
        function(method) {
          if (!method %in% names(method_labels)) {
            return(paste0(
              "Unknown method. Choose one of: ",
              toString(names(method_labels))
            ))
          }
          updateRadioButtons(session, "method", selected = method)
          paste0("Scoring method switched to ", method_labels[[method]], ".")
        },
        name = "set_method",
        description = paste(
          "Change the scoring method (re-scores every signature). ssgsea =",
          "single-sample GSEA; singscore = rank-based; zscore = module z-score;",
          "mean = mean expression of the set."
        ),
        arguments = list(
          method = ellmer::type_enum(
            names(method_labels),
            description = "The scoring method id."
          )
        )
      ),
      ellmer::tool(
        function(group_by = NULL, reference = NULL, compared_with = NULL) {
          meta <- chat_state$dataset$metadata
          cols <- setdiff(names(meta), "sample")
          # Changing the grouping variable resets its two levels to defaults, so
          # honour group_by alone; adjust levels only within the current group.
          if (!is.null(group_by)) {
            if (!group_by %in% cols) {
              return(paste0(
                "Unknown grouping column. Available: ",
                toString(cols)
              ))
            }
            updateSelectInput(session, "group_col", selected = group_by)
            return(paste0(
              "Grouping variable switched to ",
              group_by,
              "; the two contrast levels reset to that variable's defaults. Call",
              " set_contrast again with reference / compared_with to pick levels."
            ))
          }
          levs <- sort(unique(stats::na.omit(as.character(
            meta[[chat_state$group_col]]
          ))))
          changed <- character(0)
          if (!is.null(reference)) {
            if (!reference %in% levs) {
              return(paste0(
                "Unknown reference level for ",
                chat_state$group_col,
                ". Levels: ",
                toString(levs)
              ))
            }
            updateSelectInput(session, "level1", selected = reference)
            changed <- c(changed, paste0("reference = ", reference))
          }
          if (!is.null(compared_with)) {
            if (!compared_with %in% levs) {
              return(paste0(
                "Unknown 'compared with' level for ",
                chat_state$group_col,
                ". Levels: ",
                toString(levs)
              ))
            }
            updateSelectInput(session, "level2", selected = compared_with)
            changed <- c(changed, paste0("compared with = ", compared_with))
          }
          if (length(changed) == 0) {
            return("No contrast changes given.")
          }
          paste0("Contrast updated: ", toString(changed), ".")
        },
        name = "set_contrast",
        description = paste(
          "Change the group contrast. group_by is a metadata column to group",
          "samples by (e.g. group, subtype, er_status, stage); reference and",
          "compared_with are the two levels of the CURRENT grouping to contrast",
          "(difference = compared_with - reference). Changing group_by resets",
          "the levels, so set it in one call and pick levels in a follow-up call.",
          "Any argument may be omitted."
        ),
        arguments = list(
          group_by = ellmer::type_string(
            "Metadata column to group samples by.",
            required = FALSE
          ),
          reference = ellmer::type_string(
            "Reference level of the current grouping.",
            required = FALSE
          ),
          compared_with = ellmer::type_string(
            "Level compared against the reference.",
            required = FALSE
          )
        )
      ),
      ellmer::tool(
        function(signature) {
          r <- chat_state$ranking
          if (is.null(r)) {
            return("No ranking is available yet.")
          }
          idx <- match(signature, r$signature)
          if (is.na(idx)) {
            return(paste0(
              "'",
              signature,
              "' is not among the ranked signatures."
            ))
          }
          DT::selectRows(DT::dataTableProxy("ranking"), idx)
          paste0(
            "Signature detail and Pathway genes now focus ",
            signature,
            "."
          )
        },
        name = "set_signature",
        description = paste(
          "Focus a signature in the Signature detail and Pathway genes views (by",
          "selecting its row in the ranking table). Use when the user asks to",
          "look at one specific Hallmark signature."
        ),
        arguments = list(
          signature = ellmer::type_string(
            "A Hallmark signature name from the current ranking."
          )
        )
      ),
      ellmer::tool(
        function(n) {
          n <- as.character(n)
          choices <- c("15", "25", "50")
          if (!n %in% choices) {
            return(paste0("n must be one of: ", toString(choices)))
          }
          updateSelectInput(session, "ntop", selected = n)
          paste0("Score heatmap now shows the top ", n, " signatures.")
        },
        name = "set_signature_count",
        description = paste(
          "Set how many top-ranked signatures the score heatmap shows: 15, 25,",
          "or 50."
        ),
        arguments = list(
          n = ellmer::type_string(
            "Number of signatures to show: 15, 25, or 50."
          )
        )
      ),
      ellmer::tool(
        function(p_threshold = NULL, max_labels = NULL) {
          changed <- character(0)
          if (!is.null(p_threshold)) {
            p_threshold <- max(0.001, min(0.1, p_threshold))
            updateSliderInput(session, "vp", value = p_threshold)
            changed <- c(changed, paste0("significance p < ", p_threshold))
          }
          if (!is.null(max_labels)) {
            max_labels <- as.integer(max(0, min(25, max_labels)))
            updateSliderInput(session, "vlabels", value = max_labels)
            changed <- c(changed, paste0("max labels = ", max_labels))
          }
          if (length(changed) == 0) {
            return("Nothing to change for the volcano.")
          }
          paste0("Volcano updated: ", toString(changed), ".")
        },
        name = "set_volcano",
        description = paste(
          "Change the signature volcano: p_threshold is the significance cutoff",
          "(0.001-0.1); max_labels is how many top signatures to label (0-25).",
          "Either may be omitted."
        ),
        arguments = list(
          p_threshold = ellmer::type_number(
            "Significance cutoff, 0.001 to 0.1.",
            required = FALSE
          ),
          max_labels = ellmer::type_integer(
            "Number of top signatures to label, 0 to 25.",
            required = FALSE
          )
        )
      )
    )
  }

  byok_chat_server(
    "chat",
    system_prompt = sig_system_prompt,
    tools = sig_tools
  )

  # --- Ranking table -------------------------------------------------------
  output$ranking <- DT::renderDT(
    {
      df <- ranking()
      dt <- DT::datatable(
        df,
        selection = "single",
        rownames = FALSE,
        class = "cell-border stripe hover",
        extensions = "Buttons",
        options = list(
          dom = "Bfrtip",
          buttons = list("copy", "csv"),
          pageLength = 15,
          order = list()
        )
      )
      dt <- DT::formatRound(
        dt,
        c(grep("^mean_", names(df), value = TRUE), "diff"),
        digits = 3
      )
      DT::formatSignif(dt, c("pvalue", "padj"), digits = 3)
    },
    server = TRUE
  )
  # The Ranking table sits on a hidden tab; keep it rendered so its row
  # selection (and the assistant's selectRows proxy) drive the detail views.
  outputOptions(output, "ranking", suspendWhenHidden = FALSE)

  # --- Overview: a volcano of every signature (effect vs significance) ------
  # Reuse the volcano module: map the ranking's contrast onto its gene/logFC/p
  # contract (colour by significance alone, so it works across scoring methods
  # whose effect scales differ). Drop unscored sets (NA).
  volcano_df <- reactive({
    r <- ranking()
    r <- r[!is.na(r$diff) & !is.na(r$padj), , drop = FALSE]
    data.frame(
      # Short, lower-case labels (drop the HALLMARK_ prefix) so the volcano's
      # point labels stay legible and repel cleanly instead of colliding.
      gene = tolower(gsub("_", " ", sub("^HALLMARK_", "", r$signature))),
      logFC = r$diff,
      padj = r$padj,
      stringsAsFactors = FALSE
    )
  })
  volcano_server(
    "volcano",
    de_results = volcano_df,
    lfc_threshold = reactive(0),
    p_threshold = reactive(input$vp),
    p_col = reactive("padj"),
    label_top_n = reactive(input$vlabels),
    xlab = reactive(sprintf(
      "score difference (%s - %s)",
      input$level2,
      input$level1
    ))
  )

  # Selected signature: the chosen ranking row, else the top-ranked one.
  selected_sig <- reactive({
    rows <- input$ranking_rows_selected
    if (length(rows) > 0) {
      ranking()$signature[rows[1]]
    } else {
      ranking()$signature[1]
    }
  })

  # --- Score heatmap: the most differential signatures x samples -----------
  heat_rows <- reactive(utils::head(
    ranking()$signature,
    as.integer(input$ntop)
  ))
  heatmap_server(
    "heat",
    matrix = contrast_scores,
    rows = heat_rows,
    metadata = contrast_meta,
    scale = reactive("row"),
    cluster_rows = reactive(TRUE),
    group_col = reactive(input$group_col),
    # Dozens of samples per group: individual column labels are illegible and
    # collide, so hide them (the group facet strips carry the context).
    show_samples = reactive(FALSE)
  )

  # --- Signature detail: the selected signature's scores by group ----------
  output$detail_sig_label <- renderUI({
    s <- selected_sig()
    if (is.null(s) || is.na(s)) {
      return(tags$p(
        class = "text-muted small mb-2",
        "Select a signature in the Ranking table."
      ))
    }
    tags$p(
      class = "mb-2",
      "Showing ",
      tags$strong(s),
      tags$span(
        class = "text-muted small",
        " - select another Ranking row to change."
      )
    )
  })
  group_comparison_server(
    "detail",
    values = reactive(contrast_scores()[selected_sig(), ]),
    metadata = contrast_meta,
    # The panel header names the signature; keep the axis title short so the
    # long HALLMARK_ name can't overrun the (rotated) y axis.
    value_label = reactive("signature score"),
    group_col = reactive(input$group_col)
  )

  # --- Pathway genes: the selected signature's member genes -----------------
  # Which genes drive the signature's score, on the raw expression scale.
  sig_genes <- reactive(
    intersect(signatures()[[selected_sig()]], rownames(expr()))
  )
  le_expr <- reactive(expr()[, contrast_meta()$sample, drop = FALSE])
  leading <- reactive({
    shiny::validate(shiny::need(
      length(sig_genes()) > 0,
      "No member genes of this signature are in the expression matrix."
    ))
    signature_leading_edge(
      le_expr(),
      sig_genes(),
      contrast_meta()[[input$group_col]],
      input$level1,
      input$level2
    )
  })

  output$le_title <- renderText(paste(selected_sig(), "- member genes"))
  # Heatmap the top leading-edge genes (by |diff|) so it stays readable even
  # for large sets; the table beside it lists them all.
  heatmap_server(
    "genes",
    matrix = le_expr,
    rows = reactive(utils::head(leading()$gene, 30)),
    metadata = contrast_meta,
    scale = reactive("row"),
    cluster_rows = reactive(TRUE),
    group_col = reactive(input$group_col),
    show_samples = reactive(FALSE)
  )
  output$leading_edge <- DT::renderDT(
    {
      df <- leading()
      dt <- DT::datatable(
        df,
        rownames = FALSE,
        selection = "none",
        class = "cell-border stripe hover",
        extensions = "Buttons",
        options = list(
          dom = "Bfrtip",
          buttons = list("copy", "csv"),
          pageLength = 15
        )
      )
      DT::formatRound(dt, setdiff(names(df), "gene"), digits = 3)
    },
    server = TRUE
  )

  # --- Keep the assistant's state mirror current --------------------------
  # Reads reactives in a reactive context and writes plain values into the env
  # the assistant tools read (see the tool definitions above). Reactives that
  # can validate/req-fail are read defensively so the mirror never errors.
  observe({
    ds <- dataset()
    chat_state$dataset <- ds
    chat_state$dataset_label <- names(datasets)[match(input$dataset, datasets)]
    chat_state$method <- input$method
    chat_state$method_label <- unname(
      method_labels[match(input$method %||% "ssgsea", names(method_labels))]
    )
    chat_state$group_col <- input$group_col %||% "group"
    gc <- make_group_choices(ds$metadata)
    chat_state$group_label <- names(gc)[match(input$group_col, gc)]
    chat_state$level1 <- input$level1
    chat_state$level2 <- input$level2
    chat_state$ntop <- input$ntop
    chat_state$vp <- input$vp
    chat_state$vlabels <- input$vlabels
    chat_state$expr <- signature_expression_matrix(ds)
    chat_state$ranking <- tryCatch(ranking(), error = function(e) NULL)
    chat_state$contrast_meta <- tryCatch(contrast_meta(), error = function(e) {
      NULL
    })
    chat_state$selected_sig <- tryCatch(
      selected_sig(),
      error = function(e) NULL
    )
  })
}

