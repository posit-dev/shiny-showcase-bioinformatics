server <- function(input, output, session) {
  # --- Guided demo tour (the "Demo" item in the top bar) ------------------
  demo_guide <- cicerone::Cicerone$new(overlay_click_next = TRUE)$step(
    "hdr-controls",
    "1. Set the view",
    paste(
      "Start here: pick a driver gene to jump the browser to its locus, and",
      "set the minimum recurrence. Both drive the browser track and the table."
    )
  )$step(
    "hdr-dataset",
    "About this dataset",
    "A quick summary of the loaded cohort: TCGA-BRCA somatic mutations on hg19, with live variant and gene counts at the current filter."
  )$step(
    "hdr-browser",
    "Genome browser",
    "The embedded igv.js browser shows the mutation track over the reference genome. Drag to pan and scroll to zoom."
  )$step(
    "hdr-table",
    "Variant table",
    "Every variant for the focused gene at the current recurrence filter. Click a row to zoom the browser to that mutation."
  )$step(
    "open_assistant",
    "AI assistant",
    "Open the assistant (bring your own API key) to summarise the track, describe visible variants, or drive navigation for you."
  )$step(
    ".topnav .navlink[data-page='About']",
    "Learn more",
    "Finally, the About page has full data provenance, methods, and citations. That's the tour!",
    is_id = FALSE
  )
  observeEvent(input$demo, demo_guide$init()$start())

  # A plain (non-reactive) mirror of the app's current state, read by the
  # assistant's tools (kept current by the observer at the end of server()).
  chat_state <- new.env(parent = emptyenv())

  filtered <- reactive({
    mutations[mutations$count >= input$min_recur, , drop = FALSE]
  })
  gene_variants <- reactive({
    f <- filtered()
    f[f$gene == input$focus_gene, , drop = FALSE]
  })

  # At-a-glance dataset stats (live at the current recurrence filter).
  output$gx_stats <- renderUI({
    f <- filtered()
    ng <- length(unique(f$gene))
    top <- if (nrow(f) > 0) {
      names(sort(tapply(f$count, f$gene, sum), decreasing = TRUE))[1]
    } else {
      "-"
    }
    stat <- function(k, v) {
      div(class = "gx-stat", div(class = "k", k), div(class = "v", v))
    }
    div(
      class = "gx-stats",
      stat("Variants", nrow(f)),
      stat("Genes", ng),
      stat("Top gene", top)
    )
  })

  # Where the browser navigates: the focused gene's locus, a clicked variant, or
  # a coordinate range the assistant sets. Defined before the tools use it.
  locus <- reactiveVal(NULL)

  # --- Assistant: scoped, tool-using BYOK chat ----------------------------
  genome_system_prompt <- paste(
    "You are the Genome Explorer assistant, embedded in an app that shows",
    "recurrent somatic mutations from the TCGA-BRCA breast-cancer cohort in an",
    "igv.js genome browser (hg19) alongside a variant table. Your ONLY job is to",
    "help the user explore and interpret THIS app: its mutation track, the",
    "variants shown for the focused gene, and the current genomic locus.",
    "",
    "Before answering about the data, call the matching read tool for its live",
    "state: track_summary (the whole track), visible_mutations (the focused",
    "gene's variants), current_locus (where the browser is pointed). Never invent",
    "gene names, protein changes, positions, or recurrence counts -- quote the",
    "tool output. Explain protein changes (e.g. PIK3CA H1047R), recurrence, and",
    "genomic loci plainly.",
    "",
    "You can also DRIVE the browser when the user asks -- then briefly say what",
    "you changed:",
    "- navigate_to_gene: focus a driver gene (jumps the browser to its locus and",
    "  filters the variant table to it).",
    "- navigate_to_locus: navigate to an explicit chrom:start-end region.",
    "- set_recurrence_filter: keep only variants recurrent in at least N tumors",
    "  (drives the track and the table together).",
    "After changing a control, you may re-read the relevant view to interpret it.",
    "",
    "Refuse anything outside Genome Explorer and this dataset: for off-topic or",
    "general questions, briefly decline and point back to what the app can do.",
    "Be concise.",
    sep = "\n"
  )

  genome_tools <- list()
  if (requireNamespace("ellmer", quietly = TRUE)) {
    genome_tools <- list(
      ellmer::tool(
        function() {
          summarise_track(chat_state$filtered, chat_state$min_recur)
        },
        name = "track_summary",
        description = paste(
          "Summary of the whole mutation track at the current recurrence filter:",
          "variant and gene counts, and the most recurrently mutated genes."
        )
      ),
      ellmer::tool(
        function() {
          summarise_gene_variants(
            chat_state$gene_variants,
            chat_state$focus_gene
          )
        },
        name = "visible_mutations",
        description = paste(
          "Summary of the variants currently shown for the focused gene: how",
          "many, and each one's protein change, position, and recurrence count."
        )
      ),
      ellmer::tool(
        function() {
          loc <- chat_state$locus
          if (is.null(loc) || !nzchar(loc)) {
            return(paste0(
              "The browser is focused on ",
              chat_state$focus_gene,
              " (no explicit region set)."
            ))
          }
          paste0(
            "The browser is navigated to ",
            loc,
            " (hg19), currently focusing ",
            chat_state$focus_gene,
            "."
          )
        },
        name = "current_locus",
        description = paste(
          "The genomic region (chrom:start-end, hg19) the browser is currently",
          "navigated to, and the focused gene."
        )
      ),
      # --- Control tools: drive navigation and the recurrence filter. ---------
      ellmer::tool(
        function(gene) {
          if (!gene %in% genes_by_recurrence) {
            return(paste0(
              "Unknown gene. This dataset covers: ",
              toString(genes_by_recurrence)
            ))
          }
          updateSelectInput(session, "focus_gene", selected = gene)
          paste0(
            "Focused ",
            gene,
            "; the browser is navigating to its locus and the table now shows",
            " its variants."
          )
        },
        name = "navigate_to_gene",
        description = paste(
          "Focus a driver gene: jumps the igv.js browser to the gene's locus and",
          "filters the variant table to it. Use when the user names a gene to",
          "look at."
        ),
        arguments = list(
          gene = ellmer::type_enum(
            genes_by_recurrence,
            description = "The driver gene to focus."
          )
        )
      ),
      ellmer::tool(
        function(region) {
          region <- trimws(region %||% "")
          if (!grepl("^[A-Za-z0-9_]+:[0-9,]+-[0-9,]+$", region)) {
            return(paste0(
              "Region must look like chrom:start-end, e.g. chr3:178935000-",
              "178938000. Got: ",
              region
            ))
          }
          locus(region)
          paste0("Browser navigating to ", region, ".")
        },
        name = "navigate_to_locus",
        description = paste(
          "Navigate the browser to an explicit genomic region in hg19,",
          "formatted chrom:start-end (e.g. chr17:7571720-7590868). Use when the",
          "user gives coordinates rather than a gene."
        ),
        arguments = list(
          region = ellmer::type_string(
            "A genomic region as chrom:start-end (hg19)."
          )
        )
      ),
      ellmer::tool(
        function(min_tumors) {
          min_tumors <- as.integer(max(2, min(max_recurrence, min_tumors)))
          updateSliderInput(session, "min_recur", value = min_tumors)
          paste0(
            "Recurrence filter set to >= ",
            min_tumors,
            " tumors (applies to the track and the table)."
          )
        },
        name = "set_recurrence_filter",
        description = paste0(
          "Keep only variants recurrent in at least this many tumors (2 to ",
          max_recurrence,
          "). Drives both the browser track and the variant table."
        ),
        arguments = list(
          min_tumors = ellmer::type_integer(
            paste0("Minimum recurrence, 2 to ", max_recurrence, ".")
          )
        )
      )
    )
  }

  byok_chat_server(
    "chat",
    system_prompt = genome_system_prompt,
    tools = genome_tools
  )

  # --- Variant table: variants for the focused gene ------------------------
  output$variants_header <- renderText({
    sprintf("%s - %d variants", input$focus_gene, nrow(gene_variants()))
  })
  output$variants <- DT::renderDT(
    {
      DT::datatable(
        gene_variants()[, c("gene", "protein_change", "chrom", "pos", "count")],
        selection = "single",
        rownames = FALSE,
        class = "cell-border stripe hover",
        extensions = "Buttons",
        options = list(
          dom = "Bfrtip",
          buttons = list("copy", "csv"),
          pageLength = 8,
          order = list(list(4, "desc"))
        )
      )
    },
    server = TRUE
  )

  # Navigation: the focused gene's locus, or a clicked variant. (The assistant's
  # navigate_to_locus tool also writes locus directly.)
  observeEvent(input$focus_gene, locus(gene_locus(mutations, input$focus_gene)))
  observeEvent(input$variants_rows_selected, {
    gv <- gene_variants()
    row <- input$variants_rows_selected
    req(length(row) == 1, row >= 1, row <= nrow(gv))
    v <- gv[row, ]
    locus(sprintf("%s:%d-%d", v$chrom, v$pos - 60L, v$pos + 60L))
  })

  genome_browser_server("gb", mutations = filtered, locus = locus)

  # --- Keep the assistant's state mirror current --------------------------
  observe({
    chat_state$focus_gene <- input$focus_gene
    chat_state$min_recur <- input$min_recur
    chat_state$filtered <- filtered()
    chat_state$gene_variants <- gene_variants()
    chat_state$locus <- locus()
  })
}

shinyApp(ui, server)
