### Methods
- **Scoring** reduces the expression matrix + gene sets to per-sample signature
  scores by one of four dependency-free methods: **ssGSEA** (Barbie 2009),
  **singscore** (rank-based, Foroutan 2018), a **module z-score**, or the
  **mean** of the set's genes.
- **Ranking / volcano** contrast two groups per signature (difference in mean
  score + a two-sample t-test, BH-adjusted across signatures).
- **Score heatmap** shows the top signatures' scores, row z-scored and clustered.
- **Pathway genes** rank a signature's member genes by their between-group
  expression difference (its leading edge).

