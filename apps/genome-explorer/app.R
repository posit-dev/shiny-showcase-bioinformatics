mutations <- read_mutations("data")
genes_by_recurrence <- names(sort(
  tapply(mutations$count, mutations$gene, sum),
  decreasing = TRUE
))
max_recurrence <- max(mutations$count)

# A locus string (chrom:start-end) spanning a gene's variants, so navigation
# uses explicit coordinates rather than relying on igv.js gene-name lookup.
gene_locus <- function(muts, gene, flank = 2000L) {
  g <- muts[muts$gene == gene, , drop = FALSE]
  if (nrow(g) == 0) {
    return(NULL)
  }
  sprintf("%s:%d-%d", g$chrom[1], min(g$pos) - flank, max(g$pos) + flank)
}

# --- Assistant summary helpers (app-local, Shiny-free) ----------------------
summarise_track <- function(muts, min_recur) {
  if (is.null(muts) || nrow(muts) == 0) {
    return("No mutations pass the current recurrence filter.")
  }
  by_gene <- sort(tapply(muts$count, muts$gene, sum), decreasing = TRUE)
  top <- utils::head(by_gene, 8L)
  paste0(
    "Mutation track (TCGA-BRCA somatic variants, hg19), recurrence filter >= ",
    min_recur,
    " tumors: ",
    nrow(muts),
    " distinct variants across ",
    length(by_gene),
    " genes. Most recurrently mutated genes (summed tumor counts): ",
    paste(sprintf("%s (%d)", names(top), as.integer(top)), collapse = ", "),
    "."
  )
}

summarise_gene_variants <- function(gv, gene) {
  if (is.null(gv) || nrow(gv) == 0) {
    return(paste0(
      "No variants for ",
      gene,
      " pass the current recurrence filter."
    ))
  }
  o <- gv[order(gv$count, decreasing = TRUE), , drop = FALSE]
  top <- utils::head(o, 8L)
  paste0(
    gene,
    ": ",
    nrow(gv),
    " variant(s) shown on ",
    top$chrom[1],
    ", by recurrence -- ",
    paste(
      sprintf(
        "%s at %s:%d (n=%d)",
        top$protein_change,
        top$chrom,
        top$pos,
        top$count
      ),
      collapse = "; "
    ),
    "."
  )
}

# --- Assistant UI, rebuilt without bslib -----------------------------------
byok_chat_ui_plain <- function(
  id,
  title,
  subtitle = NULL,
  providers = c("gemini", "openai", "anthropic"),
  starters = NULL,
  placeholder = "Ask me anything...",
  height = "100%"
) {
  ns <- NS(id)
  providers <- .byok_chat_providers(providers)
  if (!.byok_chat_packages_ok() || length(providers) == 0) {
    return(tagList(
      div(
        class = "drawer-head",
        div(h2(title)),
        tags$button(
          class = "drawer-close",
          onclick = "GX.closeDrawer('assistant_drawer')",
          HTML("&times;")
        )
      ),
      div(
        class = "drawer-body",
        tags$p(
          "The AI assistant is off because its packages (ellmer, shinychat)",
          "are not installed."
        )
      )
    ))
  }
  choices <- .byok_chat_provider_choices(providers)
  greeting <- if (
    nzchar(.byok_chat_env_first(.byok_chat_provider_meta(providers[1])$env))
  ) {
    paste(
      "Hi! A key was found in your environment - open **Model & key** below,",
      "pick a model, and click **Connect** to start chatting."
    )
  } else {
    paste(
      "Hi! Open **Model & key** below, paste an API key, and click",
      "**Connect** to start chatting."
    )
  }
  if (length(starters) > 0) {
    cards <- paste0(
      "- <span class=\"suggestion submit\">",
      vapply(unname(starters), htmltools::htmlEscape, character(1)),
      "</span>"
    )
    greeting <- paste0(greeting, "\n\n", paste(cards, collapse = "\n"))
  }
  tagList(
    tags$style(HTML(paste0(
      "#",
      ns("chat"),
      " .shiny-tool-request,#",
      ns("chat"),
      " .shiny-tool-result{display:none !important;}"
    ))),
    div(
      class = "drawer-head",
      div(h2(title), if (!is.null(subtitle)) div(class = "sub", subtitle)),
      div(
        style = "display:flex;align-items:center;gap:0.6rem;",
        uiOutput(ns("conn_badge"), inline = TRUE),
        tags$button(
          class = "drawer-close",
          onclick = "GX.closeDrawer('assistant_drawer')",
          HTML("&times;")
        )
      )
    ),
    tags$details(
      class = "byok",
      tags$summary(icon("gear"), " Model & key"),
      div(
        class = "byok-body",
        selectInput(
          ns("provider"),
          "Provider",
          choices = choices,
          selected = unname(choices)[1]
        ),
        uiOutput(ns("key_help")),
        passwordInput(
          ns("api_key"),
          "API key",
          placeholder = "Paste your key (kept in this session only)"
        ),
        selectizeInput(
          ns("model"),
          "Model",
          choices = character(0),
          selected = character(0),
          multiple = FALSE,
          options = list(
            create = TRUE,
            placeholder = "Provider default - pick or type a model"
          )
        ),
        actionButton(
          ns("refresh_models"),
          "List models for this key",
          class = "btn-line"
        ),
        uiOutput(ns("model_source")),
        div(
          style = "display:flex;gap:0.5rem;margin:0.6rem 0;",
          actionButton(ns("connect"), "Connect", class = "btn-line btn-fill"),
          actionButton(ns("forget"), "Forget key", class = "btn-line")
        ),
        uiOutput(ns("cred_status"))
      )
    ),
    div(
      class = "drawer-body chat",
      shinychat::chat_ui(
        ns("chat"),
        height = height,
        placeholder = placeholder,
        greeting = greeting
      )
    )
  )
}

