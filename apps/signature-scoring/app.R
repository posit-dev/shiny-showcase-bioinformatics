# Signature Scoring Explorer (classic Shiny) -- composition of reusable
# component modules over one signature dataset (expression + metadata + gene-set
# signatures). Scores MSigDB Hallmark sets across samples and compares them
# between groups.
#
# App (L3) layer: page layout + wiring only. Compute lives in the logic layer
# (R/_shared, Shiny-free); UI in the component modules (R/_modules).
#
# Vendored copy. This directory is self-contained: it runs and deploys on its
# own, with its own modules and its own data. Upstream is
# posit-dev/lifescience-shiny-gallery, where R/_shared and R/_modules are
# generated by scripts/sync-shared.R and git-ignored; here they are checked in.
# Change them upstream and re-copy rather than editing them in place.

# Dev convenience: load a local, git-ignored .Renviron (e.g. BYOK API keys) from
# the app dir or any parent up to the repo root, so Sys.getenv() sees them when
# the app is launched from its own working directory. A no-op when absent -- the
# deployed bundle has none; on the gallery, set env vars in the deploy config.
local({
  dir <- normalizePath(".", mustWork = FALSE)
  repeat {
    f <- file.path(dir, ".Renviron")
    if (file.exists(f)) {
      readRenviron(f)
      break
    }
    parent <- dirname(dir)
    if (identical(parent, dir)) {
      break
    }
    dir <- parent
  }
})

