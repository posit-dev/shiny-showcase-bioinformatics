- **Pathway genes** - the selected signature's leading-edge member genes.

#### Getting started
On the **Explorer** tab, pick a scoring method and a group contrast in the
**Controls** sidebar. The activity map is front and centre, with the Ranking
table and signature Volcano a tab away; selecting a row in the Ranking tab drives
the Signature detail and Pathway genes views. Open the **Assistant** from the top
bar to ask about any view or have it drive the controls.

### Data
- **TCGA-BRCA** (`signature-brca`) - The Cancer Genome Atlas breast-invasive-
  carcinoma cohort: primary tumour vs solid-tissue normal, with clinical
  annotations (receptor subtype, ER / PR / HER2 status, stage, histology).
  Counts come from **recount3**, which uniformly re-aligns and quantifies public
  RNA-seq, so samples are directly comparable. We take VST-log2 expression and
  score the **MSigDB Hallmark** collection (50 gene sets). A curated subset -
  75 tumours balanced across the HR+ / HER2+ / TNBC receptor subtypes (25 each)
  plus 20 solid-tissue normal - ships with the app for a fast, reproducible demo
  with real subtyping power.

Prep scripts under `data/prep/` are the source of truth (provenance + licensing).

